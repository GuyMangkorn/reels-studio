#!/usr/bin/env python3
"""EDU-EP26-SHORT talk envelope (Boss, draft fix round A, 2026-11-19).

Reads the locked voice (EDU-EP26-VOICE-R3, public/narration/EDU-EP26-SHORT-narration-v1.wav, 63.13 s = 1894 f) and the
line clock (timeline-r3.json), and writes src/painted/edu26/talk26.ts: per on-screen character line (speaker != NARR) one
digit 0-9 per frame of mouth openness from the frame's RMS, normalised to the line's 95th percentile loudness. The painted
shots read it as a pure function of the composition frame (talkOpen in talk26.ts), so the mouth opens on speech and closes
in the pauses and the gaps between lines.

Usage: python3 -I scripts/edu-series/ep26/short/talk-envelope.py [--print]
"""
import json
import math
import os
import struct
import sys
import wave

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '../../../..'))
WAV = os.path.join(ROOT, 'public/narration/EDU-EP26-SHORT-narration-v1.wav')
TIMELINE = os.path.join(ROOT, 'scripts/edu-series/ep26/short/timeline-r3.json')
OUT = os.path.join(ROOT, 'src/painted/edu26/talk26.ts')
FPS = 30
FLOOR = 0.14   # share of the line's p95 RMS under which the mouth is shut (breath, room tone, the 0.20 s gaps)
SPAN = 0.95    # share above FLOOR that reaches full open
GAMMA = 0.8


def read_mono(path):
    with wave.open(path, 'rb') as w:
        n, sr, sw, ch = w.getnframes(), w.getframerate(), w.getsampwidth(), w.getnchannels()
        raw = w.readframes(n)
    if sw != 2:
        raise SystemExit(f'expected 16-bit PCM, got {sw * 8}-bit')
    s = struct.unpack(f'<{n * ch}h', raw)
    if ch > 1:
        s = [sum(s[i:i + ch]) / ch for i in range(0, len(s), ch)]
    return s, sr


def main():
    s, sr = read_mono(WAV)
    spf = sr / FPS
    lines = [r for r in json.load(open(TIMELINE)) if r['speaker'] != 'NARR']
    out = []
    for r in lines:
        a, b = round(r['start_s'] * FPS), round(r['end_s'] * FPS)
        rms = []
        for f in range(a, b):
            seg = s[int(f * spf):int((f + 1) * spf)]
            rms.append(math.sqrt(sum(x * x for x in seg) / max(1, len(seg))) / 32768)
        p95 = sorted(rms)[int(0.95 * (len(rms) - 1))] or 1e-9
        digits = ''
        for v in rms:
            o = max(0.0, min(1.0, (v / p95 - FLOOR) / SPAN)) ** GAMMA
            digits += str(min(9, int(round(o * 9))))
        out.append((r['line'], r['speaker'], a, b, digits))
        if '--print' in sys.argv:
            print(r['line'], r['speaker'], a, b, digits)
    body = '\n'.join(f"  {{line: '{l}', speaker: '{sp}', start: {a}, end: {b}, open: '{d}'}}," for l, sp, a, b, d in out)
    ts = f"""// GENERATED by scripts/edu-series/ep26/short/talk-envelope.py from the locked voice EDU-EP26-VOICE-R3
// (public/narration/EDU-EP26-SHORT-narration-v1.wav) and timeline-r3.json. Do not hand-edit: re-run the script after a voice change.
// EDU-EP26-SHORT talking mouths (Boss, draft fix round A, 2026-11-19): one digit 0-9 per composition frame of mouth openness for each
// on-screen character line (NARR lines have no mouth). `talkFace(G, line)` gives the kit `talk` mouth (`FaceState.mouth` + `open`,
// head.ts) for composition frame G: a pure function of the frame, so direct seek draws the same mouth as playback.
import type {{FaceState}} from '../kit/head';
import {{rowOf}} from './shots/index';

export type TalkLine = {{line: string; speaker: string; start: number; end: number; open: string}};
export const TALK_LINES: readonly TalkLine[] = [
{body}
];

const byLine = (id: string): TalkLine => {{
  const r = TALK_LINES.find((l) => l.line === id);
  if (!r) throw new Error(`talk26: no character line ${{id}}`);
  return r;
}};
/** Mouth openness 0..1 of line `id` at composition frame G (0 outside the line). */
export const talkOpen = (G: number, id: string): number => {{
  const r = byLine(id), i = Math.round(G) - r.start;
  return i < 0 || i >= r.open.length ? 0 : (Number(r.open[i]) / 9) * flap(i);
}};
/** Syllable flap over the voice envelope: a 6-frame (5 a second) open-close so a held vowel still moves (never below 40 % while the voice
 *  sounds); the envelope alone gates it, so the mouth is shut in every pause. */
export const flap = (i: number): number => 0.4 + 0.6 * Math.pow(Math.abs(Math.sin((Math.PI * i) / 6)), 0.6);
/** Face override for a speaker at composition frame G: the kit `talk` mouth driven by the voice while line `id` runs (shut in its
 *  pauses), else `rest` (the scene's own face state, unchanged). */
export const talkFace = (G: number, id: string, rest?: Partial<FaceState>): Partial<FaceState> | undefined => {{
  const r = byLine(id), g = Math.round(G);
  return g >= r.start && g < r.end ? {{...(rest ?? {{}}), mouth: 'talk', open: talkOpen(g, id)}} : rest;
}};
/** `talkFace` from a shot's local frame L (G = the shot's composition start + L; the shot index is the clock). */
export const talkShot = (shot: string, L: number, id: string, rest?: Partial<FaceState>) => talkFace(rowOf(shot).start + L, id, rest);
"""
    open(OUT, 'w').write(ts)
    print(f'wrote {os.path.relpath(OUT, ROOT)}: {len(out)} lines')


if __name__ == '__main__':
    main()
